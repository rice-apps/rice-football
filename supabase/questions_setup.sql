-- Draft reproducible setup for the Staff Q&A table.
-- REVIEW ONLY: this file has not been applied to any database.
-- Target only an approved development project with fictional/test data.
-- Never drop, truncate, reset, or replace the questions table.
--
-- IF public.questions already exists, the preflight below checks the app-required
-- columns, defaults, identity, primary key, and status constraint. It raises an
-- error instead of attempting to reconcile an incompatible table. Review any
-- mismatch manually and preserve existing rows. CREATE TABLE IF NOT EXISTS does
-- not migrate an existing table.
--
-- Existing policies and triggers must also be reviewed before running. This
-- setup creates no RLS policies and does not remove existing policies. The
-- hosted development table was observed with RLS enabled, no policies, and an
-- existing questions_set_updated_at trigger; that trigger is left in place.

begin;

do $preflight$
declare
  existing_table regclass := to_regclass('public.questions');
begin
  if existing_table is not null then
    if exists (
      select 1
      from (values
        ('id', 'bigint', 'NO', 'YES', 'BY DEFAULT', null::text),
        ('submitter_name', 'text', 'NO', 'NO', null::text, null::text),
        ('submitter_title', 'text', 'NO', 'NO', null::text, null::text),
        ('question', 'text', 'NO', 'NO', null::text, null::text),
        ('answer', 'text', 'YES', 'NO', null::text, null::text),
        ('status', 'text', 'NO', 'NO', null::text, '''open''::text'),
        ('created_at', 'timestamp with time zone', 'NO', 'NO', null::text, 'now()'),
        ('updated_at', 'timestamp with time zone', 'NO', 'NO', null::text, 'now()')
      ) as expected(column_name, data_type, is_nullable, is_identity, identity_generation, column_default)
      left join information_schema.columns actual
        on actual.table_schema = 'public'
       and actual.table_name = 'questions'
       and actual.column_name = expected.column_name
      where actual.column_name is null
         or actual.data_type is distinct from expected.data_type
         or actual.is_nullable is distinct from expected.is_nullable
         or actual.is_identity is distinct from expected.is_identity
         or actual.identity_generation is distinct from expected.identity_generation
         or actual.column_default is distinct from expected.column_default
    ) then
      raise exception 'public.questions does not match the reviewed Q&A schema. No setup changes were applied; inspect the table and prepare a reviewed migration.';
    end if;

    if not exists (
      select 1
      from pg_constraint
      where conrelid = existing_table
        and contype = 'p'
        and pg_get_constraintdef(oid) = 'PRIMARY KEY (id)'
    ) then
      raise exception 'public.questions is missing the expected primary key on id. No setup changes were applied.';
    end if;

    if not exists (
      select 1
      from pg_constraint
      where conrelid = existing_table
        and contype = 'c'
        and pg_get_constraintdef(oid) = 'CHECK ((status = ANY (ARRAY[''open''::text, ''in-progress''::text, ''answered''::text])))'
    ) then
      raise exception 'public.questions is missing the expected status constraint. No setup changes were applied.';
    end if;
  end if;
end
$preflight$;

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  submitter_name text not null,
  submitter_title text not null,
  question text not null,
  answer text,
  status text not null default 'open',
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint questions_status_check
    check (status in ('open', 'in-progress', 'answered'))
);

-- Keep client access denied. The app accesses Supabase only from server routes
-- using SUPABASE_SECRET_KEY, which maps to the elevated service_role.
alter table public.questions enable row level security;
grant select, insert, update on table public.questions to service_role;

-- Create an updated_at trigger only if the expected trigger is absent. The
-- hosted development project already has this trigger (using moddatetime), so
-- this block does not add a duplicate there. Review other existing triggers
-- before applying this file to any different database.
do $trigger_setup$
begin
  if not exists (
    select 1
    from pg_trigger
    where tgrelid = 'public.questions'::regclass
      and tgname = 'questions_set_updated_at'
      and not tgisinternal
  ) then
    execute $function$
      create or replace function public.questions_setup_set_updated_at()
      returns trigger
      language plpgsql
      as $body$
      begin
        new.updated_at := now();
        return new;
      end;
      $body$
    $function$;

    execute 'create trigger questions_set_updated_at before update on public.questions for each row execute function public.questions_setup_set_updated_at()';
  end if;
end
$trigger_setup$;

-- Identity inserts may need sequence usage, depending on role grants. Resolve
-- the actual identity sequence name rather than assuming its generated name.
do $sequence_grant$
declare
  identity_sequence text := pg_get_serial_sequence('public.questions', 'id');
begin
  if identity_sequence is not null then
    execute format('grant usage on sequence %s to service_role', identity_sequence);
  end if;
end
$sequence_grant$;

commit;
