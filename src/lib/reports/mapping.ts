import type { NewReport } from "@/lib/reports/validation";
import type { Report, ReportCategory, ReportKind } from "@/types/report";

// Converts between rows of the Supabase `reports` table (snake_case) and the
// app's Report shape (camelCase). Has no server-only code and makes no requests.

/** A row of the `reports` table as returned by a select of REPORT_COLUMNS. */
export type ReportRow = {
  id: string; // UUID generated by the database
  name: string;
  description: string;
  category: ReportCategory;
  kind: ReportKind;
  file_type: string;
  tags: string[];
  file_url: string | null;
  created_at: string;
  updated_at: string;
};

/** The columns a new metadata record supplies. The database fills in the rest. */
export type ReportInsert = {
  name: string;
  description: string;
  category: ReportCategory;
  kind: ReportKind;
  file_type: string;
  tags: string[];
  file_url: null;
};

export const REPORT_COLUMNS =
  "id, name, description, category, kind, file_type, tags, file_url, created_at, updated_at";

/** Converts a database row to the Report shape used by the app and API responses. */
export function toReport(row: ReportRow): Report {
  const report: Report = {
    id: row.id,
    name: row.name,
    description: row.description,
    category: row.category,
    kind: row.kind,
    fileType: row.file_type,
    tags: row.tags,
    createdAt: row.created_at,
  };
  // Left off entirely when there is no file, so cards offer no link to open.
  if (row.file_url !== null) report.fileUrl = row.file_url;
  return report;
}

/**
 * Converts validated metadata to the columns to insert. The selected file is
 * not stored, so a new submission never has a file URL. The id and timestamps
 * are left to the database.
 */
export function toReportInsert(report: NewReport): ReportInsert {
  return {
    name: report.name,
    description: report.description,
    category: report.category,
    kind: report.kind,
    file_type: report.fileType,
    tags: report.tags,
    file_url: null,
  };
}
